export const MAX_IZNOS_CENTI = 500000;

export function izracunajTotal(korpa) {
  if (!Array.isArray(korpa) || korpa.length === 0) {
    throw new Error('Korpa je prazna.');
  }
  if (korpa.length > 50) {
    throw new Error('Previše različitih artikala u korpi.');
  }

  let ukupno = 0;
  const stavke = [];

  for (const red of korpa) {
    const proizvod = KATALOG[red?.id];
    if (!proizvod) {
      throw new Error(`Nepoznat proizvod: ${red?.id}`);
    }

    const kolicina = Number(red.kolicina ?? 1);
    if (!Number.isInteger(kolicina) || kolicina < 1 || kolicina > 20) {
      throw new Error(`Neispravna količina za ${red.id}`);
    }

    ukupno += proizvod.cijena * kolicina;
    stavke.push(`${kolicina}x ${proizvod.naziv}`);
  }

  if (ukupno < 100) {
    throw new Error('Iznos je premali.');
  }
  if (ukupno > MAX_IZNOS_CENTI) {
    throw new Error('Iznos prelazi dozvoljeni maksimum.');
  }

  return {
    amount: ukupno,
    opis: stavke.join(', ').slice(0, 100),
  };
}
